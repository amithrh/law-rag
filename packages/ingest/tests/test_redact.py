# --- Bank account ------------------------------------------------------------

class TestBankAccountRedaction:
    def test_redacts_long_number_near_keyword(self) -> None:
        text = "Account No: 12345678901234 holding the disputed deposit."
        result = redact(text)
        assert "[BANK A/C REDACTED]" in result.text

    def test_does_not_redact_long_number_without_keyword(self) -> None:
        # Without a bank keyword nearby, we don't redact long digit runs
        # (too many false positives — case numbers, transaction IDs, etc.).
        text = "Order page 12345678901234 of the file."
